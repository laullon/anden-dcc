#!/usr/bin/env python3
"""Embed the self-contained web UI in flash; run after editing web/ assets."""
from pathlib import Path
import argparse
import re
ROOT = Path(__file__).resolve().parents[1]

def page_text():
    page=(ROOT/'web/index.html').read_text()
    templates='\n'.join('<template id="art-'+kind+'">'+(ROOT/'web/locos'/(kind+'.svg')).read_text().strip()+'</template>' for kind in ['electric','diesel','steam'])
    page,count=re.subn(r'<!-- LOCO_ART_START -->.*?<!-- LOCO_ART_END -->',lambda _: '<!-- LOCO_ART_START -->\n'+templates+'\n<!-- LOCO_ART_END -->',page,flags=re.S)
    assert count==1,'Missing locomotive-art markers'
    return page

def generate():
    pieces = ['// Generated by tools/embed_web.py; edit web/ instead.\n#pragma once\n']
    for name, filename in [('PAGE', 'index.html'), ('ICON_SVG', 'icon.svg'), ('FAVICON_SVG', 'favicon.svg')]:
        text = page_text() if name=='PAGE' else (ROOT / 'web' / filename).read_text()
        assert ')WEB"' not in text
        pieces.append(f'const char {name}[] = R"WEB({text})WEB";\n')
    data = (ROOT / 'web/favicon.ico').read_bytes()
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i+16]) for i in range(0, len(data), 16)]
    pieces.append('const uint8_t FAVICON_ICO[] = {\n  ' + ',\n  '.join(rows) + '\n};\n')
    return '\n'.join(pieces)

if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    target=ROOT/'firmware/anden-dcc/WebAssets.h'
    output=generate()
    icon = ROOT/'assets/icon.svg'
    if args.check:
        if (ROOT/'web/index.html').read_text()!=page_text():
            raise SystemExit('Locomotive art is stale; run python3 tools/embed_web.py')
        if not icon.exists() or icon.read_text() != (ROOT/'web/icon.svg').read_text():
            raise SystemExit('assets/icon.svg is stale; run python3 tools/embed_web.py')
        if not target.exists() or target.read_text()!=output:
            raise SystemExit('WebAssets.h is stale; run python3 tools/embed_web.py')
    else:
        (ROOT/'web/index.html').write_text(page_text())
        target.write_text(output)
        icon.parent.mkdir(exist_ok=True)
        icon.write_text((ROOT/'web/icon.svg').read_text())
