#!/usr/bin/env python3
"""Embed the ESP page, shared loco SVGs, and deterministic gzip in flash."""
import argparse,gzip,re
from pathlib import Path
root=Path(__file__).resolve().parent
repo=root.parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
path=root/'web/index.html';original=path.read_text()
art='\n'.join('<template id="art-'+kind+'">'+(repo/'web/locos'/f'{kind}.svg').read_text().strip()+'</template>' for kind in ['electric','diesel','steam'])
html=re.sub(r'<!-- LOCO_ART_START -->.*?<!-- LOCO_ART_END -->','<!-- LOCO_ART_START -->\n'+art+'\n<!-- LOCO_ART_END -->',original,flags=re.S)
data=gzip.compress(html.encode(),mtime=0)
header = """// Generated by embed.py; edit web/index.html.
#pragma once
#include <Arduino.h>
#include <stddef.h>
#include <stdint.h>

extern const uint8_t SETUP_PAGE[] PROGMEM;
extern const size_t SETUP_PAGE_SIZE;
"""
result = '// Generated by embed.py; edit web/index.html.\n#include "SetupPage.h"\n\nconst uint8_t SETUP_PAGE[] PROGMEM = {\n'
result += '\n'.join('  '+','.join(str(b) for b in data[i:i+20])+',' for i in range(0,len(data),20))+'\n};\n'
result += 'const size_t SETUP_PAGE_SIZE = sizeof(SETUP_PAGE);\n'
output = root / 'SetupPage.cpp'
interface = root / 'SetupPage.h'
if args.check:
    # Compare inflated data because zlib versions may encode it differently.
    try:
        stored = output.read_text().split('{',1)[1].rsplit('}',1)[0]
        fresh = gzip.decompress(bytes(int(v) for v in re.findall(r'\d+',stored))) == html.encode()
    except (OSError,ValueError,IndexError,EOFError):
        fresh = False
    if html != original or not fresh or interface.read_text() != header:
        raise SystemExit('ESP13 assets stale; run embed.py')
else:
    path.write_text(html)
    interface.write_text(header)
    output.write_text(result)
