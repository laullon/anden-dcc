"""Exercise the cab OLED driver and label codec with captured I2C writes."""
from pathlib import Path
import subprocess
import os
import tempfile

root = Path(__file__).resolve().parents[1]
with tempfile.TemporaryDirectory(prefix='anden-display-') as directory:
    folder = Path(directory)
    (folder / 'avr').mkdir()
    (folder / 'Arduino.h').write_text("""
#pragma once
#include <stdint.h>
extern uint32_t clockMs;
inline uint32_t millis() { return clockMs; }
""")
    (folder / 'avr/pgmspace.h').write_text("""
#pragma once
#define PROGMEM
#define pgm_read_byte(address) (*(address))
""")
    (folder / 'display.cpp').write_text("""
#include <cassert>
#include <cstring>
#include <iostream>
#include "CabI2c.h"
#include <vector>
#include "CabLabel.h"
#include "CabDisplay.h"
uint32_t clockMs = 0;
struct Capture {
  std::vector<std::vector<uint8_t>> transactions;
  bool fail = false;
} capture;
void CabI2c::begin() {}
bool CabI2c::write(uint8_t address, const uint8_t* bytes, uint8_t count) {
  assert(address == 0x3C && count <= MAX_BYTES);
  capture.transactions.emplace_back(bytes, bytes + count);
  return !capture.fail;
}
int main() {
  CabDisplay display;
  display.begin();
  const auto& init = capture.transactions.front();
  bool mux = false, com = false;
  for (unsigned i = 1; i + 1 < init.size(); ++i) {
    if (init[i] == 0xA8) mux = init[i + 1] == 63;
    if (init[i] == 0xDA) com = init[i + 1] == 0x12;
  }
  assert(mux && com);
  unsigned cleared[8] = {};
  for (unsigned i = 1; i + 1 < capture.transactions.size(); ++i) {
    const auto& bytes = capture.transactions[i];
    assert(bytes[0] == 0x80 && bytes[6] == 0x40);
    unsigned page = bytes[1] & 15;
    assert(page < 8);
    for (unsigned j = 7; j < bytes.size(); ++j) assert(bytes[j] == 0);
    cleared[page] += bytes.size() - 7;
  }
  for (unsigned count : cleared) assert(count == 128);
  char hex[CabLabel::LENGTH * 2 + 1], label[CabLabel::LENGTH + 1];
  CabLabel::encode(hex, "Santa F\\xC3\\xA9");
  assert(CabLabel::decode(label, hex) && !strcmp(label, "SANTA FE"));
  CabLabel::encode(hex, "Ni\\xC3\\xB1o");
  assert(CabLabel::decode(label, hex) && !strcmp(label, "NINO"));
  CabLabel::encode(hex, "abcdefghijklmnopq");
  assert(CabLabel::decode(label, hex) && !strcmp(label, "ABCDEFGHIJKLMNOP"));
  CabLabel::encode(hex, "");
  assert(CabLabel::decode(label, hex) && !strcmp(label, "LOCOMOTIVE"));
  CabLabel::encode(hex, "\\xF0\\x9F\\x9A\\x82");
  assert(CabLabel::decode(label, hex) && !strcmp(label, "?"));
  assert(!CabLabel::decode(label, "00") && !strcmp(label, "?"));
  assert(!CabLabel::decode(label, "GG") && !strcmp(label, "?"));

  auto redraw = [&](uint8_t address, uint8_t speed, const char* name) {
    capture.transactions.clear();
    for (unsigned i = 0; i < 48; ++i) {
      clockMs += 5;
      display.update(address, speed, name);
      assert(capture.transactions.size() == i + 1);
      const auto& bytes = capture.transactions.back();
      assert((bytes[1] & 15) == i / 6);
    }
    unsigned char frame[8][128] = {};
    for (const auto& bytes : capture.transactions) {
      unsigned page = bytes[1] & 15, x = bytes[3] | ((bytes[5] & 15) << 4);
      for (unsigned i = 7; i < bytes.size(); ++i) frame[page][x++] = bytes[i];
    }
    clockMs += 5;
    display.update(address, speed, name);
    assert(capture.transactions.size() == 48);
    // Emit the pixels generated by production code for optional visual review.
    for (const auto& page : frame)
      for (auto byte : page) std::cout << unsigned(byte) << ' ';
    std::cout << '\\n';
    // Rounded frame and a continuous fill, with third markers at x=45/82.
    assert(frame[6][8] == 0x80 && frame[7][8] == 0x07);
    const unsigned filled = speed * 106 / 3;
    for (unsigned x = 11; x < 117; ++x) {
      const bool lit = (frame[6][x] & 0xC0) && (frame[7][x] & 0x0F);
      assert(lit == (x < 11 + filled));
    }
    // Text such as STEP/STOP/ON/OFF must not occupy the speed's side margins.
    for (unsigned p = 2; p <= 5; ++p)
      for (unsigned x = 0; x < 40; ++x)
        assert(frame[p][x] == 0 && frame[p][127 - x] == 0);
    return std::vector<unsigned char>(frame[0], frame[0] + 128);
  };
  auto longName = redraw(3, 0, "SANTA FE");
  redraw(3, 2, "SANTA FE");
  auto shortName = redraw(3, 2, "333");
  assert(longName != shortName);
  // A shorter centred name clears columns occupied by the old label.
  assert(shortName[20] == 0);
  redraw(3, 1, "SANTA FE");
  redraw(3, 3, "SANTA FE");
  redraw(6, 0, "");
  redraw(6, 0, "ABCDEFGHIJKLMNOP");
  redraw(0, 0, "");
  CabDisplay absent;
  capture.fail = true;
  absent.begin();
  auto count = capture.transactions.size();
  clockMs += 5;
  absent.update(3, 0, "TEST");
  assert(capture.transactions.size() == count);
}
""")
    subprocess.run([os.environ.get('CXX', 'c++'), '-std=c++11', '-include', 'cassert',
                    '-I', str(folder), '-I', str(root / 'firmware/uno-stack-test'),
                    '-I', str(root / 'libraries/AndenStackLink/src'),
                    str(folder / 'display.cpp'),
                    str(root / 'firmware/uno-stack-test/CabDisplay.cpp'),
                    str(root / 'libraries/AndenStackLink/src/CabLabel.cpp'),
                    '-o', str(folder / 'display')], check=True)
    result = subprocess.run([str(folder / 'display')], check=True, capture_output=True, text=True)
    if os.environ.get('CAB_DISPLAY_PREVIEW'):
        Path(os.environ['CAB_DISPLAY_PREVIEW']).write_text(result.stdout)
print('PASS: OLED initialization, complete redraws, yellow/blue layout, bounded writes, label encoding, shorter-name clearing, speed bar and absent display.')
