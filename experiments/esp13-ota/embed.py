#!/usr/bin/env python3
"""Embed the ESP13 setup page without changing the Pico web assets."""
import argparse
from pathlib import Path

root = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
html = (root / 'web/index.html').read_text()
assert ')ESP13"' not in html
result = '// Generated by embed.py; edit web/index.html.\n#pragma once\n'
result += 'static const char SETUP_PAGE[] PROGMEM = R"ESP13(' + html + ')ESP13";\n'
output = root / 'SetupPage.h'
if args.check:
    if not output.exists() or output.read_text() != result:
        raise SystemExit('ESP13 setup page is stale; run experiments/esp13-ota/embed.py')
else:
    output.write_text(result)
